// Pixel icons rendered from ASCII grids — crisp at any size.
function Px({ rows, className = "" }: { rows: string[]; className?: string }) {
  return (
    <svg viewBox="0 0 16 16" className={className} shapeRendering="crispEdges" aria-hidden="true">
      {rows.map((row, y) =>
        [...row].map((c, x) =>
          c === "." ? null : <rect key={`${x}-${y}`} x={x} y={y} width={1.05} height={1.05} fill="currentColor" />
        )
      )}
    </svg>
  );
}

