export function ActionIcon({ action, className }: { action: Action; className?: string }) {
  switch (action) {
    case "fwd":
      return <IconFwd className={className} />;
    case "back":
      return <IconBack className={className} />;
    case "jump":
      return <IconJump className={className} />;
    case "dodge":
      return <IconDodge className={className} />;
    case "strike":
      return <IconStrike className={className} />;
    case "block":
      return <IconBlock className={className} />;
    case "roll":
      return <IconRoll className={className} />;
    case "cleave":
      return <IconCleave className={className} />;
    case "bash":
      return <IconBash className={className} />;
    case "reflect":
      return <IconReflect className={className} />;
    case "rest":
      return <IconRest className={className} />;
    case "wait":
      return <IconWait className={className} />;
  }
}
